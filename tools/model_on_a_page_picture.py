#: A canon code in brackets on the picture: "(G1)", "(R5, R6)", "(CO1)". Steer of 26 Oct: the
#: front door shows plain names; the codes stay in the canon page, the alt text and the band
#: sheets one tap down. Only bracketed codes, so an SVG path's "M0,0" is never touched.
CANON_CODE = re.compile(r" ?\((?:[A-Z]{1,2}\d+)(?:,\s*[A-Z]{1,2}\d+)*\)")


def build(doc: Path = DOC, map_path: Path = _MAP, sheets: Path = SHEETS) -> str:
    return CANON_CODE.sub("", render(load_spec(doc), map_atom_levels(map_path), sheets))


def write(out: Path = OUT) -> bool:
    """Publish step. Fail closed: a spec the generator refuses leaves the previous picture served."""
    try:
        svg = build()
    except (PictureSpecError, OSError, yaml.YAMLError) as exc:
        print("MODEL-ON-A-PAGE PICTURE NOT WRITTEN: {}".format(exc), file=sys.stderr)
        return False
    if not out.exists() or out.read_text(encoding="utf-8") != svg:
        out.write_text(svg, encoding="utf-8")
    return True


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the served picture is not the generated one")
    args = ap.parse_args(argv)
    if args.check:
        same = OUT.read_text(encoding="utf-8") == build()
        print("model-on-a-page.svg {}".format("is the generated picture" if same else "DIFFERS from the generated picture"))
        return 0 if same else 1
    return 0 if write() else 1


if __name__ == "__main__":
    sys.exit(main())
