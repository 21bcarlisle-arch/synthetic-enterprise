# marker glyph and its colour, by computed stage
MARK = {LIVE: (".", BLUE), BUILDING: ("_", GREEN)}
NOT_STARTED = ("~", AMBER)
STAGE_WORD = {LIVE: "done", BUILDING: "in build"}


class PictureSpecError(ValueError):
    pass


def load_spec(doc: Path = DOC) -> dict:
    _, head, rest = doc.read_text(encoding="utf-8").partition("\n## The picture")
    _, fence, rest = rest.partition("\n```yaml\n")
    block, close, _ = rest.partition("\n```")
    if not (head and fence and close):
        raise PictureSpecError("{} has no ```yaml block under '## The picture'".format(doc))
    return yaml.safe_load(block)


def stage_of(atoms: list[str], levels: dict) -> str:
    if not atoms:
        raise PictureSpecError("a stated line names no atom, so the map cannot give its state")
    return compute_stage([levels.get(a, _UNKNOWN_ATOM) for a in atoms])


def mark(atoms, levels):
    return MARK.get(stage_of(atoms, levels), NOT_STARTED)


def _t(s: str) -> str:
    """Escape, then **bold** -> a bold tspan."""
    return re.sub(r"\*\*(.+?)\*\*", r'<tspan font-weight="700">\1</tspan>', escape(s, quote=False))


def _fit(lines, room, where):
    if len(lines) > room:
        raise PictureSpecError("{} has {} lines and room for {}".format(where, len(lines), room))
    return lines


def text(x, y, s, size, fill=INK, **kw):
    attrs = "".join(' {}="{}"'.format(k.replace("_", "-"), v) for k, v in kw.items())
    return '<text x="{}" y="{}" font-size="{}"{} fill="{}">{}</text>'.format(x, y, size, attrs, fill, _t(s))


def _band_link(band: str, body: list[str], sheets: Path) -> list[str]:
    if not (sheets / band / "index.html").exists():
        return body
    return ['<a href="./model/{}/" target="_top" aria-label="Open the {} sheet">'.format(band, band)] + \
        ["  " + b for b in body] + ["</a>"]


