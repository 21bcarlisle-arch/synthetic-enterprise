"""The published map page: generated, reachable from How it's built, and every link opens a concept.

The defect this names: the page served at /model/map/ drifting from the generator (a hand edit),
or a tap on a connection that opens nothing. Run against the committed page, not a fixture.
"""
from __future__ import annotations

import re
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent
PAGE = SITE / "model" / "map" / "index.html"


def test_the_map_page_is_generated_and_every_tap_opens_a_concept():
    """MUTATION: delete a panel from the page and its links point nowhere, so this fires; strip
    every link and the non-empty assert fires."""
    html = PAGE.read_text(encoding="utf-8")
    assert "Generated by tools/the_map_page.py" in html
    targets = set(re.findall(r'href="#(c-[^"]+)"', html))
    assert targets, "the map page renders no concept link"
    missing = targets - set(re.findall(r'id="(c-[^"]+)"', html))
    assert not missing, f"links that open no concept: {sorted(missing)}"


def test_how_its_built_links_to_the_map():
    """MUTATION: remove the link from /harness/ and the page is unreachable, so this fires."""
    assert 'href="../model/map/"' in (SITE / "harness" / "index.html").read_text(encoding="utf-8")
